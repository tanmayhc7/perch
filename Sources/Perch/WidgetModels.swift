/// The weather for one city you type in, from Open-Meteo (free, no account). Only the city name and then its
/// coordinates are sent to open-meteo.com, and only while the widget is on and the notch is opened.
@MainActor @Observable
final class WeatherModel {
    enum State: Equatable { case needsCity, loading, ready, failed }
    struct Place: Codable, Equatable { var name: String; var latitude: Double; var longitude: Double }
    struct Now: Equatable { var temperature: Double; var feelsLike: Double; var high: Double; var low: Double; var code: Int; var isDay: Bool }

    private(set) var state: State
    private(set) var place: Place?
    private(set) var now: Now?
    var useFahrenheit: Bool { Locale.current.measurementSystem == .us }
    @ObservationIgnored var onAlert: ((Toast) -> Void)?
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private var fetched: Date?
    @ObservationIgnored private var running = false

    init(defaults: UserDefaults) {
        self.defaults = defaults
        let saved = defaults.data(forKey: "weatherPlace").flatMap { try? JSONDecoder().decode(Place.self, from: $0) }
        place = saved
        state = saved == nil ? .needsCity : .loading
    }

    func chooseCity() {
        let alert = NSAlert()
        alert.messageText = "Weather for which city?"
        alert.informativeText = "Perch looks the city up on open-meteo.com. Nothing else is sent."
        let field = NSTextField(frame: NSRect(x: 0, y: 0, width: 280, height: 24))
        field.placeholderString = "City, e.g. Pune"
        field.stringValue = place?.name ?? ""
        alert.accessoryView = field
        alert.addButton(withTitle: "Use this city")
        alert.addButton(withTitle: "Cancel")
        NSApp.activate(ignoringOtherApps: true)
        alert.window.initialFirstResponder = field
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        use(city: field.stringValue)
    }

    func use(city: String) {
        let q = city.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return }
        state = .loading
        Task {
            if let p = await Self.geocode(q) {
                place = p
                defaults.set(try? JSONEncoder().encode(p), forKey: "weatherPlace")
                refresh(force: true)
            } else {
                state = place == nil ? .needsCity : .ready
                onAlert?(Toast(symbol: "magnifyingglass", tint: .warning, title: "Couldn't find “\(q)”", subtitle: "Try the city name on its own"))
            }
        }
    }

    func refresh(force: Bool = false) {
        guard let place, !running, force || fetched == nil || Date().timeIntervalSince(fetched!) > 1800 else { return }
        running = true
        if now == nil { state = .loading }
        let f = useFahrenheit
        Task {
            let result = await Self.forecast(place, fahrenheit: f)
            running = false
            if let result { now = result; fetched = Date(); state = .ready } else if now == nil { state = .failed }
        }
    }

    private static let session: URLSession = {
        let c = URLSessionConfiguration.ephemeral
        c.timeoutIntervalForRequest = 15
        return URLSession(configuration: c)
    }()

    nonisolated private static func geocode(_ name: String) async -> Place? {
        var c = URLComponents(string: "https://geocoding-api.open-meteo.com/v1/search")!
        c.queryItems = [.init(name: "name", value: name), .init(name: "count", value: "1"), .init(name: "language", value: "en"), .init(name: "format", value: "json")]
        guard let url = c.url, let (data, _) = try? await session.data(from: url),
              let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let r = (root["results"] as? [[String: Any]])?.first,
              let lat = r["latitude"] as? Double, let lon = r["longitude"] as? Double else { return nil }
        return Place(name: (r["name"] as? String) ?? name, latitude: lat, longitude: lon)
    }

    nonisolated private static func forecast(_ p: Place, fahrenheit: Bool) async -> Now? {
        var c = URLComponents(string: "https://api.open-meteo.com/v1/forecast")!
        c.queryItems = [
            .init(name: "latitude", value: String(p.latitude)), .init(name: "longitude", value: String(p.longitude)),
            .init(name: "current", value: "temperature_2m,apparent_temperature,weather_code,is_day"),
            .init(name: "daily", value: "temperature_2m_max,temperature_2m_min"),
            .init(name: "temperature_unit", value: fahrenheit ? "fahrenheit" : "celsius"),
            .init(name: "timezone", value: "auto"), .init(name: "forecast_days", value: "1"),
        ]
        guard let url = c.url, let (data, _) = try? await session.data(from: url),
              let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let cur = root["current"] as? [String: Any], let daily = root["daily"] as? [String: Any],
              let t = cur["temperature_2m"] as? Double, let hi = (daily["temperature_2m_max"] as? [Double])?.first,
              let lo = (daily["temperature_2m_min"] as? [Double])?.first else { return nil }
        return Now(temperature: t, feelsLike: cur["apparent_temperature"] as? Double ?? t, high: hi, low: lo,
                   code: cur["weather_code"] as? Int ?? 0, isDay: (cur["is_day"] as? Int ?? 1) == 1)
    }

    /// A weather symbol and a few words for a WMO weather code.
    static func describe(_ code: Int, isDay: Bool) -> (symbol: String, text: String) {
        switch code {
        case 0: (isDay ? "sun.max.fill" : "moon.stars.fill", "Clear")
        case 1, 2: (isDay ? "cloud.sun.fill" : "cloud.moon.fill", "Partly cloudy")
        case 3: ("cloud.fill", "Overcast")
        case 45, 48: ("cloud.fog.fill", "Fog")
        case 51...57: ("cloud.drizzle.fill", "Drizzle")
        case 61...67: ("cloud.rain.fill", "Rain")
        case 71...77, 85, 86: ("cloud.snow.fill", "Snow")
        case 80...82: ("cloud.heavyrain.fill", "Showers")
        case 95...99: ("cloud.bolt.rain.fill", "Thunderstorm")
        default: ("cloud.fill", "Cloudy")
        }
    }

    func loadSample() {
        place = Place(name: "Pune", latitude: 18.52, longitude: 73.86)
        now = Now(temperature: 27, feelsLike: 29, high: 31, low: 21, code: 2, isDay: true)
        state = .ready
    }
}

// MARK: - Volume and brightness

/// The output volume (through Core Audio) and the built-in display's brightness (through the system's
/// DisplayServices library, which has no public header). Either is left out where the Mac has no such control.
@MainActor @Observable
final class ControlsModel {
    private(set) var volume: Float?
    private(set) var muted = false
    private(set) var brightness: Float?
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var dragging = false

    func start() {
        guard timer == nil else { return }
        read()
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.read() }
        }
    }

    func stop() { timer?.invalidate(); timer = nil }

    func read() {
        guard !dragging else { return }
        if let d = Self.outputDevice() {
            volume = Self.getFloat(d, Self.volumeSelector)
            muted = Self.getUInt32(d, kAudioDevicePropertyMute) == 1
        } else { volume = nil }
        brightness = Self.getBrightness()
    }

    func setVolume(_ v: Float, final: Bool = false) {
        dragging = !final
        volume = v
        guard let d = Self.outputDevice() else { return }
        _ = Self.setFloat(d, Self.volumeSelector, v)
        // Moving the slider up from silence should be heard.
        if muted && v > 0 { setMuted(false) }
    }

    func setMuted(_ m: Bool) {
        guard let d = Self.outputDevice() else { return }
        var value: UInt32 = m ? 1 : 0
        var a = Self.address(kAudioDevicePropertyMute)
        if AudioObjectHasProperty(d, &a) { AudioObjectSetPropertyData(d, &a, 0, nil, UInt32(MemoryLayout<UInt32>.size), &value); muted = m }
    }

    func setBrightness(_ v: Float, final: Bool = false) {
        dragging = !final
        brightness = v
        Self.setBrightnessValue(v)
    }

    // Core Audio. 'vmvc' is the "virtual main volume" the system's own volume keys use.
    private static let volumeSelector = AudioObjectPropertySelector(0x766D_7663)

    private static func address(_ selector: AudioObjectPropertySelector) -> AudioObjectPropertyAddress {
        AudioObjectPropertyAddress(mSelector: selector, mScope: kAudioDevicePropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
    }

    private static func outputDevice() -> AudioDeviceID? {
        var id = AudioDeviceID(0)
        var size = UInt32(MemoryLayout<AudioDeviceID>.size)
        var a = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultOutputDevice,
                                           mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
        guard AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &a, 0, nil, &size, &id) == noErr, id != 0 else { return nil }
        return id
    }

