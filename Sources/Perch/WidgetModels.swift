    // Brightness: DisplayServices is private, so it's looked up at run time and the control hides if it's missing.
    private typealias GetBrightness = @convention(c) (UInt32, UnsafeMutablePointer<Float>) -> Int32
    private typealias SetBrightness = @convention(c) (UInt32, Float) -> Int32
    private static let displayServices = dlopen("/System/Library/PrivateFrameworks/DisplayServices.framework/DisplayServices", RTLD_LAZY)

    private static func builtInDisplay() -> UInt32? {
        for s in NSScreen.screens {
            if let n = s.deviceDescription[NSDeviceDescriptionKey("NSScreenNumber")] as? NSNumber, CGDisplayIsBuiltin(n.uint32Value) != 0 {
                return n.uint32Value
            }
        }
        return nil
    }

    private static func getBrightness() -> Float? {
        guard let lib = displayServices, let sym = dlsym(lib, "DisplayServicesGetBrightness"), let id = builtInDisplay() else { return nil }
        var v: Float = 0
        return unsafeBitCast(sym, to: GetBrightness.self)(id, &v) == 0 ? v : nil
    }

    private static func setBrightnessValue(_ v: Float) {
        guard let lib = displayServices, let sym = dlsym(lib, "DisplayServicesSetBrightness"), let id = builtInDisplay() else { return }
        _ = unsafeBitCast(sym, to: SetBrightness.self)(id, v)
    }

