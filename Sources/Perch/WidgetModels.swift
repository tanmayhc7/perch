/// The models behind the Nest's widgets. Each does nothing until its widget is switched on, and nothing
/// while the notch is closed (apart from the clipboard, which has to watch to remember what you copied).
@MainActor @Observable
final class WidgetHub {
    let clipboard = ClipboardModel()
    let github = GitHubModel()
    let system = SystemModel()
    let weather: WeatherModel
    let controls = ControlsModel()
    @ObservationIgnored var isOn: (Widget) -> Bool = { _ in false }

    init(defaults: UserDefaults = .standard) { weather = WeatherModel(defaults: defaults) }

    func start() {
        clipboard.isOn = { [weak self] in self?.isOn(.clipboard) ?? false }
        weather.onAlert = onAlert
        clipboard.start()
    }

    @ObservationIgnored var onAlert: ((Toast) -> Void)? {
        didSet { weather.onAlert = onAlert }
    }

    /// The notch opened, or a widget was switched on while it was open: bring the ones that are on up to date.
    func opened() {
        if isOn(.github) { github.refresh() }
        if isOn(.weather) { weather.refresh() }
        if isOn(.system) { system.start() } else { system.stop() }
        if isOn(.controls) { controls.start() } else { controls.stop() }
        if !isOn(.clipboard) { clipboard.clear() }
    }

    func closed() {
        system.stop()
        controls.stop()
    }
}

// MARK: - Clipboard

/// The last things you copied, as text. Kept in memory only (never written to disk), and left out when an
/// app marks a copy as a secret (password managers do), or when the widget is off.
@MainActor @Observable
final class ClipboardModel {
    struct Item: Identifiable, Equatable {
        let id = UUID()
        var text: String
    }

    static let limit = 10
    static let maxLength = 4_000
    /// Pasteboard types apps add to a copy that shouldn't be remembered.
    private static let skip: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private(set) var items: [Item] = []
    /// The item just copied back, for a moment, so its row can say so.
    private(set) var copied: UUID?
    @ObservationIgnored var isOn: () -> Bool = { false }
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastCount = NSPasteboard.general.changeCount

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.5
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard isOn() else { items = []; return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skip), let text = pb.string(forType: .string) else { return }
        add(text)
    }

    func add(_ text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxLength else { return }
        items.removeAll { $0.text == text }
        items.insert(Item(text: text), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts an item back on the clipboard (and at the top of the list).
    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastCount = pb.changeCount
        add(item.text)
        let id = items.first?.id
        copied = id
        Task {
            try? await Task.sleep(for: .seconds(1.2))
            if copied == id { copied = nil }
        }
    }

    func clear() { items = [] }

    func loadSample() {
        items = ["git rebase --onto main feature~3 feature", "https://github.com/tanmayhc7/perch/pull/11", "Roadmap sync notes — Thursday", "ssh deploy@staging.example.com", "#FF8C52"].map { Item(text: $0) }
    }
}

