/// Pull requests waiting for your review and your own open ones with their CI state, read through the
/// GitHub command line (`gh`) you're already signed in with. Nothing is read until the widget is on.
@MainActor @Observable
final class GitHubModel {
    enum State: Equatable { case idle, loading, missing, signedOut, failed(String), ready }
    enum CI { case passing, failing, pending }
    struct PR: Identifiable, Equatable {
        var id: String { url.absoluteString }
        var number: Int
        var title: String
        var repo: String
        var url: URL
        var ci: CI?
    }

    private(set) var state: State = .idle
    private(set) var toReview: [PR] = []
    private(set) var mine: [PR] = []
    private(set) var reviewCount = 0
    @ObservationIgnored private var fetched: Date?
    @ObservationIgnored private var running = false

    func refresh(force: Bool = false) {
        guard !running, force || fetched == nil || Date().timeIntervalSince(fetched!) > 90 else { return }
        running = true
        if toReview.isEmpty && mine.isEmpty { state = .loading }
        Task {
            let result = await Task.detached { Self.fetch() }.value
            running = false
            fetched = Date()
            switch result {
            case .success(let r): toReview = r.review; mine = r.mine; reviewCount = r.count; state = .ready
            case .failure(let e): state = e.state
            }
        }
    }

    struct Fetched: Sendable { var review: [PR]; var mine: [PR]; var count: Int }
    struct Failure: Error, Sendable { var state: State }

    private static let query = """
    query {
      viewer { pullRequests(first: 5, states: OPEN, orderBy: {field: UPDATED_AT, direction: DESC}) {
        nodes { number title url repository { nameWithOwner }
          commits(last: 1) { nodes { commit { statusCheckRollup { state } } } } } } }
      review: search(query: "is:pr is:open archived:false review-requested:@me", type: ISSUE, first: 5) {
        issueCount
        nodes { ... on PullRequest { number title url repository { nameWithOwner } } } }
    }
    """

    nonisolated static func ghPath() -> String? {
        let home = FileManager.default.homeDirectoryForCurrentUser.path
        return ["/opt/homebrew/bin/gh", "/usr/local/bin/gh", "\(home)/.local/bin/gh", "/usr/bin/gh"]
            .first { FileManager.default.isExecutableFile(atPath: $0) }
    }

    nonisolated private static func fetch() -> Result<Fetched, Failure> {
        guard let path = ghPath() else { return .failure(Failure(state: .missing)) }
        let p = Process()
        p.executableURL = URL(fileURLWithPath: path)
        p.arguments = ["api", "graphql", "-f", "query=\(query)"]
        var env = ProcessInfo.processInfo.environment
        env["GH_PROMPT_DISABLED"] = "1"
        env["GH_NO_UPDATE_NOTIFIER"] = "1"
        p.environment = env
        let out = Pipe(), err = Pipe()
        p.standardOutput = out
        p.standardError = err
        do { try p.run() } catch { return .failure(Failure(state: .failed(error.localizedDescription))) }
        // A hung network shouldn't leave a process behind.
        let killer = DispatchWorkItem { if p.isRunning { p.terminate() } }
        DispatchQueue.global().asyncAfter(deadline: .now() + 25, execute: killer)
        let data = out.fileHandleForReading.readDataToEndOfFile()
        let errText = String(decoding: err.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        p.waitUntilExit()
        killer.cancel()
        guard p.terminationStatus == 0 else {
            let lower = errText.lowercased()
            if lower.contains("gh auth login") || lower.contains("authentication") || lower.contains("not logged") {
                return .failure(Failure(state: .signedOut))
            }
            let line = errText.split(separator: "\n").first.map(String.init) ?? "GitHub didn't answer"
            return .failure(Failure(state: .failed(String(line.prefix(120)))))
        }
        guard let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any], let d = root["data"] as? [String: Any] else {
            return .failure(Failure(state: .failed("Unexpected answer from GitHub")))
        }
        func pr(_ n: [String: Any], ci: Bool) -> PR? {
            guard let number = n["number"] as? Int, let title = n["title"] as? String,
                  let u = (n["url"] as? String).flatMap(URL.init(string:)) else { return nil }
            let repo = ((n["repository"] as? [String: Any])?["nameWithOwner"] as? String) ?? ""
            var state: CI?
            if ci, let commits = (n["commits"] as? [String: Any])?["nodes"] as? [[String: Any]],
               let rollup = ((commits.first?["commit"] as? [String: Any])?["statusCheckRollup"] as? [String: Any])?["state"] as? String {
                switch rollup {
                case "SUCCESS": state = .passing
                case "FAILURE", "ERROR": state = .failing
                default: state = .pending
                }
            }
            return PR(number: number, title: title, repo: repo, url: u, ci: state)
        }
        let mine = (((d["viewer"] as? [String: Any])?["pullRequests"] as? [String: Any])?["nodes"] as? [[String: Any]] ?? [])
            .compactMap { pr($0, ci: true) }
        let review = (d["review"] as? [String: Any]) ?? [:]
        let toReview = (review["nodes"] as? [[String: Any]] ?? []).compactMap { pr($0, ci: false) }
        return .success(Fetched(review: toReview, mine: mine, count: review["issueCount"] as? Int ?? toReview.count))
    }

    func loadSample() {
        func pr(_ n: Int, _ t: String, _ repo: String, _ ci: CI?) -> PR { PR(number: n, title: t, repo: repo, url: URL(string: "https://github.com/\(repo)/pull/\(n)")!, ci: ci) }
        toReview = [pr(42, "Add retry to the sync job", "acme/api", nil), pr(7, "Fix flaky login test", "acme/web", nil)]
        mine = [pr(11, "Nest: a second slide", "me/perch", .passing), pr(12, "Clipboard history", "me/perch", .pending), pr(9, "Updater", "me/perch", .failing)]
        reviewCount = 2
        state = .ready
    }
}

// MARK: - System

/// Battery, processor and memory load, free disk space and the battery of connected Bluetooth devices
/// (AirPods and the like). It samples every two seconds, only while the notch is open and the widget is on.
@MainActor @Observable
final class SystemModel {
    struct Device: Identifiable, Equatable { var id: String { name }; var name: String; var percent: Int }

    private(set) var batteryPercent: Int?
    private(set) var charging = false
    private(set) var cpu: Double = 0
    private(set) var memory: Double = 0
    /// 1 normal, 2 warning, 4 critical (macOS's own memory pressure levels).
    private(set) var pressure = 1
    private(set) var diskFreeGB: Double?
    private(set) var devices: [Device] = []
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastTicks: (busy: UInt64, total: UInt64)?
    @ObservationIgnored private var devicesFetched: Date?
    @ObservationIgnored private var devicesRunning = false

    func start() {
        guard timer == nil else { return }
        sample()
        timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.sample() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        lastTicks = nil
    }

    func sample() {
        readBattery()
        readCPU()
        readMemory()
        if let v = try? URL(fileURLWithPath: "/").resourceValues(forKeys: [.volumeAvailableCapacityForImportantUsageKey]),
           let free = v.volumeAvailableCapacityForImportantUsage {
            diskFreeGB = Double(free) / 1_000_000_000
        }
        refreshDevices()
    }

    private func readBattery() {
        let info = IOPSCopyPowerSourcesInfo().takeRetainedValue()
        let sources = IOPSCopyPowerSourcesList(info).takeRetainedValue() as [CFTypeRef]
        for s in sources {
            guard let d = IOPSGetPowerSourceDescription(info, s)?.takeUnretainedValue() as? [String: Any],
                  d[kIOPSTypeKey] as? String == kIOPSInternalBatteryType,
                  let now = d[kIOPSCurrentCapacityKey] as? Int, let max = d[kIOPSMaxCapacityKey] as? Int, max > 0 else { continue }
            batteryPercent = Int((Double(now) / Double(max) * 100).rounded())
            charging = (d[kIOPSIsChargingKey] as? Bool) ?? false
            return
        }
        batteryPercent = nil
    }

    private func readCPU() {
        var info = host_cpu_load_info()
        var count = mach_msg_type_number_t(MemoryLayout<host_cpu_load_info>.size / MemoryLayout<integer_t>.size)
        let r = withUnsafeMutablePointer(to: &info) {
            $0.withMemoryRebound(to: integer_t.self, capacity: Int(count)) { host_statistics(mach_host_self(), HOST_CPU_LOAD_INFO, $0, &count) }
        }
        guard r == KERN_SUCCESS else { return }
        let t = info.cpu_ticks
        let busy = UInt64(t.0) + UInt64(t.1) + UInt64(t.3), total = busy + UInt64(t.2)
        if let last = lastTicks, total > last.total {
            cpu = Double(busy - last.busy) / Double(total - last.total)
        }
        lastTicks = (busy, total)
    }

    private func readMemory() {
        var stats = vm_statistics64()
        var count = mach_msg_type_number_t(MemoryLayout<vm_statistics64>.size / MemoryLayout<integer_t>.size)
        let r = withUnsafeMutablePointer(to: &stats) {
            $0.withMemoryRebound(to: integer_t.self, capacity: Int(count)) { host_statistics64(mach_host_self(), HOST_VM_INFO64, $0, &count) }
        }
        if r == KERN_SUCCESS {
            let page = UInt64(vm_kernel_page_size)
            let used = (UInt64(stats.active_count) + UInt64(stats.wire_count) + UInt64(stats.compressor_page_count)) * page
            memory = min(1, Double(used) / Double(ProcessInfo.processInfo.physicalMemory))
        }
        var level: Int32 = 1
        var size = MemoryLayout<Int32>.size
        if sysctlbyname("kern.memorystatus_vm_pressure_level", &level, &size, nil, 0) == 0 { pressure = Int(level) }
    }

    /// `system_profiler` is slow (about a second), so it runs off the main thread, at most every two minutes.
    private func refreshDevices() {
        guard !devicesRunning, devicesFetched == nil || Date().timeIntervalSince(devicesFetched!) > 120 else { return }
        devicesRunning = true
        Task {
            let found = await Task.detached { Self.bluetoothDevices() }.value
            devicesRunning = false
            devicesFetched = Date()
            devices = found
        }
    }

    func loadSample() {
        batteryPercent = 78; charging = false; cpu = 0.34; memory = 0.62; pressure = 1; diskFreeGB = 312
        devices = [Device(name: "AirPods Pro", percent: 84)]
    }

    nonisolated static func bluetoothDevices() -> [Device] {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/sbin/system_profiler")
        p.arguments = ["-json", "SPBluetoothDataType"]
        let out = Pipe()
        p.standardOutput = out
        p.standardError = FileHandle.nullDevice
        guard (try? p.run()) != nil else { return [] }
        let data = out.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        return parseDevices(data)
    }

    nonisolated static func parseDevices(_ data: Data) -> [Device] {
        guard let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let sections = root["SPBluetoothDataType"] as? [[String: Any]] else { return [] }
        var found: [Device] = []
        for section in sections {
            for entry in section["device_connected"] as? [[String: Any]] ?? [] {
                for (name, v) in entry {
                    guard let props = v as? [String: Any] else { continue }
                    // AirPods report left, right and case; everything else reports one level. Show the lowest of the buds.
                    let levels = props.filter { $0.key.hasPrefix("device_batteryLevel") }
                        .compactMap { k, v -> (String, Int)? in
                            guard let s = v as? String, let n = Int(s.trimmingCharacters(in: CharacterSet(charactersIn: "% "))) else { return nil }
                            return (k, n)
                        }
                    let buds = levels.filter { !$0.0.hasSuffix("Case") }.map(\.1)
                    if let low = buds.min() { found.append(Device(name: name, percent: low)) }
                }
            }
        }
        return found.sorted { $0.name < $1.name }
    }
}

